// Ported from Netlib fdlibm 5.3 e_atan2.c.
pub(crate) fn atan2(y: f64, x: f64) -> f64 {
    const PI: f64 = 3.1415926535897931160e0;
    const PI_LO: f64 = 1.2246467991473531772e-16;
    if x.is_nan() || y.is_nan() {
        return x + y;
    }
    let hx = hi(x);
    let lx = lo(x);
    let hy = hi(y);
    let ly = lo(y);
    if (hx.wrapping_sub(0x3ff0_0000) | lx) == 0 {
        return atan(y);
    }
    let ix = hx & 0x7fff_ffff;
    let iy = hy & 0x7fff_ffff;
    let m = ((hy >> 31) & 1) | ((hx >> 30) & 2);
    if (iy | ly) == 0 {
        return match m {
            0 | 1 => y,
            2 => PI,
            _ => -PI,
        };
    }
    if (ix | lx) == 0 {
        return if hy < 0 { -PI / 2.0 } else { PI / 2.0 };
    }
    if ix == 0x7ff0_0000 {
        if iy == 0x7ff0_0000 {
            return match m {
                0 => PI / 4.0,
                1 => -PI / 4.0,
                2 => 3.0 * PI / 4.0,
                _ => -3.0 * PI / 4.0,
            };
        }
        return match m {
            0 => 0.0,
            1 => -0.0,
            2 => PI,
            _ => -PI,
        };
    }
    if iy == 0x7ff0_0000 {
        return if hy < 0 { -PI / 2.0 } else { PI / 2.0 };
    }
    let k = (iy - ix) >> 20;
    let z = if k > 60 {
        PI / 2.0 + 0.5 * PI_LO
    } else if hx < 0 && k < -60 {
        0.0
    } else {
        atan((y / x).abs())
    };
    match m {
        0 => z,
        1 => -z,
        2 => PI - (z - PI_LO),
        _ => (z - PI_LO) - PI,
    }
}
// Ported from Netlib fdlibm 5.3 s_cbrt.c.
pub(crate) fn cbrt(mut x: f64) -> f64 {
    const B1: i32 = 715094163;
    const B2: i32 = 696219795;
    const C: f64 = 5.42857142857142815906e-01;
    const D: f64 = -7.05306122448979611050e-01;
    const E: f64 = 1.41428571428571436819e0;
    const F: f64 = 1.60714285714285720630e0;
    const G: f64 = 3.57142857142857150787e-01;
    let mut hx = hi(x);
    let sign = hx & i32::MIN;
    hx ^= sign;
    if hx >= 0x7ff0_0000 {
        return x + x;
    }
    if (hx | lo(x)) == 0 {
        return x;
    }
    x = with_hi(x, hx);
    let mut t = if hx < 0x0010_0000 {
        let mut scaled = with_hi(0.0, 0x4350_0000) * x;
        scaled = with_hi(scaled, hi(scaled) / 3 + B2);
        scaled
    } else {
        with_hi(0.0, hx / 3 + B1)
    };
    let r = t * t / x;
    let s = C + r * t;
    t *= G + F / (s + E + D / s);
    t = with_lo(t, 0);
    t = with_hi(t, hi(t) + 1);
    let s = t * t;
    let r = x / s;
    let w = t + t;
    t += t * ((r - t) / (w + r));
    with_hi(t, hi(t) | sign)
}
pub(crate) fn pow(x: f64, y: f64) -> f64 {
    if y.is_nan() {
        x + y
    } else if x.abs() == 1.0 && y.is_infinite() {
        f64::NAN
    } else {
        libm::pow(x, y)
    }
}
