#[test]
fn a_type_resolves_through_its_import_whatever_shadows_the_value() {
    let temp = super::TestTempDir::new("pklr_test_import_type_matrix");
    std::fs::write(
        temp.path().join("m.pkl"),
        "class C {}\ntypealias A = Int\nlocal class LC {}\nlocal typealias LA = Int\nlocal Secret = C\n",
    )
    .unwrap();
    std::fs::write(temp.path().join("o.pkl"), "class D {}\nx = 1\n").unwrap();
    let main = temp.path().join("main.pkl");
    let mut failures = Vec::new();
    for (shadow, ty, op, value, expected) in IMPORTED {
        let expr = format!("{value} {op} {ty}");
        let body = match *shadow {
            "let" => format!("r = let (m = 0) ({expr})"),
            "obj" => format!("r = let (m = new Dynamic {{ C = 1; A = 2 }}) ({expr})"),
            "for" => format!("r = new Listing {{ for (m in List(0)) {{ {expr} }} }}"),
            "param" => format!("function f(m) = {expr}\nr = f(0)"),
            "map" => format!("r = let (m = Map()) ({expr})"),
            "list" => format!("r = let (m = List()) ({expr})"),
            "this" => format!("r = let (m = this) ({expr})"),
            "mod" => format!("r = let (m = module) ({expr})"),
            "inst" => format!("r = let (m = inst) ({expr})"),
            "other" => format!("r = let (m = o) ({expr})"),
            _ => format!("r = {expr}"),
        };
        std::fs::write(
            &main,
            format!("import \"m.pkl\"\nimport \"o.pkl\"\nlocal inst = new m.C {{}}\n{body}\n"),
        )
        .unwrap();
        let got = match pklr::eval_to_json(&main) {
            Ok(json) => json["r"].to_string(),
            Err(_) => "ERR".to_string(),
        };
        let want = if *expected == "ERR" {
            "ERR".to_string()
        } else {
            serde_json::from_str::<serde_json::Value>(expected)
                .unwrap()
                .to_string()
        };
        if got != want {
            failures.push(format!("{shadow} {expr}: pkl {want}, pklr {got}"));
        }
    }
    assert!(
        failures.is_empty(),
        "{} cells differ:\n{}",
        failures.len(),
        failures.join("\n")
    );
}
