#[test]
fn quoted_and_unquoted_types_match_pkl_across_every_use() {
    let mut failures = Vec::new();
    for (ty, shape, value, expected) in CELLS {
        let body = match *shape {
            "def" => format!("class K {{ p: {ty} }}\nr = new K {{}}.p"),
            "ampy" => format!("class K {{ p: {ty} }}\nr = new K {{ p {{ y = 5 }} }}.p"),
            "ampl" => format!("class K {{ p: {ty} }}\nr = new K {{ p {{ 1 }} }}.p"),
            "is" => format!("r = {value} is {ty}"),
            "isf" => format!("function f(x) = x is {ty}\nr = f({value})"),
            "as" => format!("r = {value} as {ty}"),
            other => panic!("unknown shape {other}"),
        };
        let src = format!("{HEADER}{body}");
        let mut evaluator = pklr::eval::Evaluator::new();
        let result = evaluator.eval_source(&src, std::path::Path::new("test.pkl"));
        let got = match result {
            Ok(value) => value.to_json()["r"].to_string(),
            Err(_) => "ERR".to_string(),
        };
        let want = if *expected == "ERR" {
            "ERR".to_string()
        } else {
            serde_json::from_str::<serde_json::Value>(expected)
                .unwrap()
                .to_string()
        };
        if got != want {
            failures.push(format!("{shape} {value} {ty}: pkl {want}, pklr {got}"));
        }
    }
    assert!(
        failures.is_empty(),
        "{} cells differ:\n{}",
        failures.len(),
        failures.join("\n")
    );
}
