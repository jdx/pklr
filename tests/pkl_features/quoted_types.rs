#[test]
fn shadowed_built_ins_and_unresolved_quoted_names_match_pkl() {
    let mut failures = Vec::new();
    for (declarations, ty, shape, value, expected) in SHADOWED {
        let body = match *shape {
            "def" => format!("class K {{ p: {ty} }}\nr = new K {{}}.p"),
            "ampx" => format!("class K {{ p: {ty} }}\nr = new K {{ p {{ x = 5 }} }}.p"),
            "ampl" => format!("class K {{ p: {ty} }}\nr = new K {{ p {{ 1 }} }}.p"),
            "is" => format!("r = {value} is {ty}"),
            "as" => format!("r = {value} as {ty}"),
            other => panic!("unknown shape {other}"),
        };
        let src = format!("{declarations}\n{body}");
        let mut evaluator = pklr::eval::Evaluator::new();
        let got = match evaluator.eval_source(&src, std::path::Path::new("test.pkl")) {
            Ok(value) => value.to_json()["r"].to_string(),
            Err(_) => "ERR".to_string(),
        };
        let want = if *expected == "ERR" {
            "ERR".to_string()
        } else {
            serde_json::from_str::<serde_json::Value>(expected)
                .unwrap()
                .to_string()
        };
        if got != want {
            failures.push(format!(
                "{declarations} / {shape} {value} {ty}: pkl {want}, pklr {got}"
            ));
        }
    }
    assert!(
        failures.is_empty(),
        "{} cells differ:\n{}",
        failures.len(),
        failures.join("\n")
    );
}

